#!/usr/bin/env python3
"""Generate both browser consumers from the single terminology resource schema."""
import argparse
import hashlib
import json
from pathlib import Path

SCHEMA = Path(__file__).resolve().parents[1] / 'cedar-terminology-server-core/src/main/resources/contracts/terminology-links.schema.json'


def emit(node):
    if '$ref' in node:
        return node['$ref'].rsplit('/', 1)[1]
    if 'const' in node:
        return json.dumps(node['const'])
    if 'enum' in node:
        return ' | '.join(map(json.dumps, node['enum']))
    if node.get('type') == 'object':
        properties = node.get('properties', {})
        if node.get('oneOf'):
            return ' | '.join(
                '{ ' + ' '.join(f'readonly {key}?: never;' for key in properties) + ' }'
                if variant.get('maxProperties') == 0
                else emit({**node, **variant, 'oneOf': None})
                for variant in node['oneOf']
            )
        required = node.get('required', [])
        return '{\n' + '\n'.join(
            f'  readonly {key}{"" if key in required else "?"}: {emit(value)};'
            for key, value in properties.items()
        ) + '\n}'
    if 'oneOf' in node:
        return ' | '.join(emit(variant) for variant in node['oneOf'])
    if node.get('type') == 'string':
        return 'string'
    raise ValueError(f'Unsupported schema: {node}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('outputs', nargs='+', type=Path)
    args = parser.parse_args()
    raw = SCHEMA.read_bytes()
    schema = json.loads(raw)
    output = ('/* eslint-disable prettier/prettier */\n'
              '// Generated by cedar-terminology-server/tools/generate-terminology-types.py. Do not edit.\n'
              f'// Schema SHA-256: {hashlib.sha256(raw).hexdigest()}\n\n')
    canonical = SCHEMA.parents[6] / 'cedar-model-validation-library/schema/valueConstraintsLinksFieldContent.json'
    if canonical.exists() and schema['$defs']['ConstraintLinks'] != json.loads(canonical.read_text()):
        raise SystemExit('Links schema differs from the core CEDAR model')
    output += "import type { ConstraintLinks } from 'cedar-model-typescript-library';\nexport type { ConstraintLinks } from 'cedar-model-typescript-library';\n\n"
    output += '\n\n'.join(f'export type {name} = {emit(node)};' for name, node in schema['$defs'].items() if name != 'ConstraintLinks') + '\n'
    for path in args.outputs:
        if args.check:
            if not path.exists() or path.read_text() != output:
                raise SystemExit(f'Stale generated contract: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output)


if __name__ == '__main__':
    main()
